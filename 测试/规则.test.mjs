import 测试 from 'node:test';
import 断言 from 'node:assert/strict';
import { 旅程, 判定落点, 结算, 蓄力距离, 距离蓄力 } from '../dist/规则.mjs';
const 平台 = { 横: 0, 纵: 0, 半宽: 70, 半深: 35, 形状: '圆' };
const 正中 = 游戏 => 游戏.准备穿越(距离蓄力(Math.hypot(游戏.目标.横 - 游戏.位置.横, 游戏.目标.纵 - 游戏.位置.纵)));
测试('普通落点加1分，并中断中心连击', () => {
  断言.deepEqual(结算(12, 3, '普通'), { 分数: 13, 连击: 0, 增加: 1, 完成: false });
});
测试('连续正中按2、4、6分递增', () => {
  let 分数 = 0, 连击 = 0;
  for (const 期望 of [2, 4, 6, 8]) { const 结果 = 结算(分数, 连击, '中心');断言.equal(结果.增加, 期望);({ 分数, 连击 } = 结果); }
  断言.equal(分数, 20);
});
测试('圆形和方形平台使用各自边界，边缘属于平台', () => {
  断言.equal(判定落点(平台, { 横: 0, 纵: 0 }), '中心');
  断言.equal(判定落点(平台, { 横: 70, 纵: 0 }), '普通');
  断言.equal(判定落点(平台, { 横: 70.1, 纵: 0 }), '保护');
  断言.equal(判定落点({ ...平台, 形状: '方' }, { 横: 35, 纵: 18 }), '保护');
});
测试('过短与过长均延长平台保护，保留分数并清零连击', () => {
  for (const 时长 of [0, 1600, 10000]) {
    const 游戏 = new 旅程(() => .5);游戏.分数 = 23;游戏.连击 = 4;
    const 穿越 = 游戏.准备穿越(时长);断言.equal(穿越.判定, '保护');
    const 结果 = 游戏.完成穿越();断言.equal(结果.增加, 0);断言.equal(游戏.分数, 23);断言.equal(游戏.连击, 0);
    断言.equal(游戏.当前.延伸.length, 1);断言.deepEqual(游戏.位置, 穿越.落点);断言.equal(游戏.完成, false);
    正中(游戏);断言.equal(游戏.完成穿越().增加, 2);
  }
});
测试('动画未完成不计分，重复输入与重复结算不能刷分', () => {
  const 游戏 = new 旅程(() => .5);正中(游戏);断言.equal(游戏.分数, 0);断言.equal(游戏.准备穿越(1000), null);
  游戏.完成穿越();断言.equal(游戏.分数, 2);断言.equal(游戏.完成穿越(), null);断言.equal(游戏.分数, 2);
});
测试('中心奖励跨过门槛时封顶299，下一平台放置冬冬', () => {
  const 游戏 = new 旅程(() => .5);游戏.分数 = 298;游戏.连击 = 12;正中(游戏);游戏.完成穿越();
  断言.equal(游戏.分数, 299);断言.equal(游戏.目标.终点, true);断言.equal(游戏.完成, false);
});
测试('终点连续落空不误通关，保留同一冬冬并能再次成功', () => {
  const 游戏 = new 旅程(() => .5);游戏.分数 = 298;正中(游戏);游戏.完成穿越();const 终点 = 游戏.目标;
  for (const 时长 of [0, 1600, 0]) {
    游戏.准备穿越(时长);游戏.完成穿越();断言.equal(游戏.分数, 299);断言.equal(游戏.完成, false);断言.equal(游戏.目标, 终点);
  }
  正中(游戏);const 结果 = 游戏.完成穿越();断言.equal(结果.完成, true);断言.equal(游戏.分数, 300);断言.equal(游戏.准备穿越(500), null);
});
测试('完整中心通关与重新开始', () => {
  const 游戏 = new 旅程(() => .5);
  for (let 步 = 0; 步 < 18; 步++) { 正中(游戏);游戏.完成穿越(); }
  断言.equal(游戏.分数, 300);断言.equal(游戏.完成, true);
  const 新游戏 = new 旅程();断言.equal(新游戏.分数, 0);断言.equal(新游戏.连击, 0);断言.equal(新游戏.保护次数, 0);
});
测试('蓄力有上限，距离换算一致，中心永远可达', () => {
  断言.equal(蓄力距离(-100), 24);断言.equal(蓄力距离(10000), 464);
  for (let 序号 = 0; 序号 < 100; 序号++) {
    const 游戏 = new 旅程();const 距离 = Math.hypot(游戏.目标.横, 游戏.目标.纵);
    断言.ok(Math.abs(蓄力距离(距离蓄力(距离)) - 距离) < .001);
  }
});
